#!/usr/bin/env python3
"""Draws the GS - Trails images (own content, pure stdlib PNG) and writes content/gs-trails/trails.json.
   python3 tools/make_gs_trails.py"""
import json, os, struct, zlib

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "content", "gs-trails")
W, H = 128, 32

def png(rows):
    raw = b"".join(b"\x00" + bytes(r) for r in rows)
    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 6, 0, 0, 0)) \
        + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")

def lerp(a, b, t):
    return [int(a[i] + (b[i] - a[i]) * t) for i in range(3)]

def make(c0, c1, stripes=False):
    rows = []
    for y in range(H):
        v = abs((y + 0.5) / H * 2 - 1)           # 0 centre, 1 edge
        row = []
        for x in range(W):
            t = x / (W - 1)                       # 0 head, 1 tail
            r, g, b = lerp(c0, c1, t)
            a = (1.0 - v * v) * (1.0 - t)
            if stripes and (x // 8) % 2:
                a *= 0.6
            row += [r, g, b, int(255 * max(0.0, min(1.0, a)))]
        rows.append(row)
    return png(rows)

TRAILS = [
    ("ember", "Ember", (255, 220, 120), (255, 60, 20), False, "#ffffff", "add"),
    ("frost", "Frost", (220, 250, 255), (60, 140, 255), False, "#ffffff", "add"),
    ("toxic", "Toxic", (200, 255, 120), (40, 180, 90), True, "#ffffff", "mix"),
    ("violet", "Violet", (255, 170, 255), (110, 40, 200), False, "#ffffff", "add"),
]
os.makedirs(OUT, exist_ok=True)
index = []
for id_, title, c0, c1, st, col, blend in TRAILS:
    name = id_ + ".png"
    with open(os.path.join(OUT, name), "wb") as f:
        f.write(make(c0, c1, st))
    index.append({"id": id_, "title": title, "image": name, "width": 0.4, "lifetime": 1.5, "color": col,
                  "blend": blend, "access": "public", "price": 0, "credit": "generated by tools/make_gs_trails.py",
                  "licence": "MIT", "author": "TMC", "url": "https://github.com/zees-games/dot-trail"})
with open(os.path.join(OUT, "trails.json"), "w") as f:
    json.dump({"trails": index}, f, indent="\t")
    f.write("\n")
